// Release signing lives in a gitignored keystore.properties (see
// keystore.properties.example) — never committed, so a release build
// simply isn't possible without it present locally. Loaded lazily/
// nullably so debug builds (and CI checks that only need assembleDebug)
// keep working without it.
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        keystorePropertiesFile.inputStream().use { load(it) }
    }
}

android {
    namespace = "com.wealthfolio.mobile"
    compileSdk = 36

    defaultConfig {
        applicationId = "com.wealthfolio.mobile"
        minSdk = 26
        targetSdk = 36
        versionCode = 1
        versionName = "1.0"
    }

    signingConfigs {
        create("release") {
            if (keystorePropertiesFile.exists()) {
                storeFile = rootProject.file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        debug {
            // Local dev backend — your Mac's LAN IP, since a physical
            // phone can't resolve `localhost` as itself. Emulators also
            // reach this fine (unlike literal `localhost`).
            buildConfigField("String", "API_BASE_URL", "\"http://192.168.1.155:8080/api/v1/\"")
            buildConfigField("String", "WEB_ORIGIN", "\"http://192.168.1.155:5173\"")
        }
        release {
            isMinifyEnabled = false
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            if (keystorePropertiesFile.exists()) {
                signingConfig = signingConfigs.getByName("release")
            }
            buildConfigField("String", "API_BASE_URL", "\"https://etherna.id/api/v1/\"")
            buildConfigField("String", "WEB_ORIGIN", "\"https://etherna.id\"")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    kotlinOptions {
        jvmTarget = "17"
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }
}

